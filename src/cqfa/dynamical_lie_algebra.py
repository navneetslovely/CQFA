"""Dynamical Lie algebra primitives and the gradient-variance law.

The algebra is obtained by Lie closure, Hilbert-Schmidt vectorised: an
orthonormal basis is maintained, each operator flattened to a length-d**2
vector under <A,B> = Tr[A^dag B] = vec(A)^dag vec(B), and a bracket is added
only when it raises the rank.

Three properties this module encodes:

  (1) The circuit algebra of the hardware-efficient ansatz is su(2^n), of
      dimension 4^n - 1, but only when the fixed CNOT-ring entangler is
      included. The rotation generators {i Y_q, i Z_q} alone close to the
      3n-dimensional algebra of commuting single-qubit rotations and never
      entangle distinct qubits, so ``hea_circuit_generators`` adds the
      entangler-conjugated copies E g E^dag. Without them the barren plateau
      of the generic ansatz is invisible.

  (2) The frame-induced restricted algebra g_G of the symmetrised commutant
      ansatz on H_+ = range(Pi) is small: for z2_pauli(n) it is 3(n-1), linear
      in n, while dim(H_+) = 2^{n-1} grows exponentially.

  (3) The default observable Z_0 restricted to H_+ can be orthogonal to g_G,
      giving P_g(Z_0) = 0 for the Z2 family, in which case the restricted
      model cannot move that loss. A trainability statement therefore requires
      an observable with support in the reachable algebra; ``g_purity`` lets a
      caller check P_g(M) > 0 and choose M accordingly.

References
----------
Larocca et al., Quantum 6, 824 (2022), arXiv:2105.14377 (Lie closure).
Ragone et al., Nat. Commun. 15, 7172 (2024), arXiv:2309.09342
    (variance law Var = P_g(rho) P_g(O) / dim(g), Eq. 10; g-purity Eq. 7).
Fontana et al., Nat. Commun. 15, 7171 (2024), arXiv:2309.07902 (adjoint rep).
"""
from __future__ import annotations

import numpy as np

from .group import X, Y, Z  # noqa: F401  (X kept for completeness / callers)
from .simulator import cnot_ring, embed_1q


# ---------------------------------------------------------------------------
# Lie-closure engine (Larocca 2022 Algorithm 1, HS-vectorised)
# ---------------------------------------------------------------------------
def _vec(M: np.ndarray) -> np.ndarray:
    return np.asarray(M).reshape(-1).astype(complex)


def _orthonormal_add(basis: list, M: np.ndarray, tol: float = 1e-9) -> bool:
    """Gram-Schmidt `M` (as an HS vector) against the current orthonormal
    `basis`; append the normalised residual iff it is non-negligible.

    Returns True iff `M` enlarged the span.
    """
    v = _vec(M)
    for b in basis:
        v = v - (b.conj() @ v) * b
    nv = np.linalg.norm(v)
    if nv > tol:
        basis.append(v / nv)
        return True
    return False


def lie_closure_dim(generators, tol: float = 1e-9, cap: int | None = None):
    """Dimension of the Lie algebra generated by `generators`.

    Parameters
    ----------
    generators : sequence of (d, d) complex arrays
        Anti-Hermitian generators {i H_mu} (the closure is a real Lie algebra,
        but we store complex HS vectors; the span dimension is what we return).
    tol : float
        Rank tolerance for the HS Gram-Schmidt.
    cap : int | None
        Hard cap on the basis size (memory guard).  When the closure reaches
        `cap`, the routine stops and returns `cap` (the caller should flag the
        row as capped).  Defaults to d**2 (never binds for the sizes here).

    Returns
    -------
    (dim, basis_rows) : (int, (dim, d**2) complex array)
        `dim` = dimension of the algebra (or `cap` if capped); `basis_rows` is
        the orthonormal HS basis, one row per algebra element.
    """
    generators = [np.asarray(g, dtype=complex) for g in generators]
    if len(generators) == 0:
        return 0, np.zeros((0, 0), dtype=complex)
    d2 = generators[0].size
    cap = d2 if cap is None else int(cap)

    basis: list = []
    frontier = [g for g in generators if _orthonormal_add(basis, g, tol)]
    while frontier and len(basis) < cap:
        new_frontier = []
        for A in generators:
            for B in frontier:
                if len(basis) >= cap:
                    break
                C = A @ B - B @ A                       # Lie bracket [A, B]
                if np.linalg.norm(C) > tol and _orthonormal_add(basis, C, tol):
                    new_frontier.append(C)
        frontier = new_frontier
    dim = min(len(basis), cap)
    return dim, np.array(basis[:cap]) if basis else np.zeros((0, d2), dtype=complex)


# ---------------------------------------------------------------------------
# generator sets for the hardware-efficient ansatz
# ---------------------------------------------------------------------------
def rotation_generators(n: int):
    """Rotation generators {i Y_q, i Z_q : q} of the RY/RZ ansatz.

    Note: these alone close to only the 3n-dimensional algebra of commuting
    single-qubit rotations, NOT su(2^n).  Use `hea_circuit_generators` for the
    true circuit DLA.
    """
    gens = []
    for q in range(n):
        gens.append(1j * embed_1q(Y, q, n))
        gens.append(1j * embed_1q(Z, q, n))
    return gens


def hea_circuit_generators(n: int, include_entangler: bool = True):
    """Circuit-DLA generators of the hardware-efficient ansatz.

    With `include_entangler=True` (default, CORRECT), returns the rotation
    generators together with their CNOT-ring conjugates {E g E^dag}, so the Lie
    closure is su(2^n) (dim 4^n - 1) exactly -- the generic-HEA barren plateau.

    With `include_entangler=False`, returns rotation generators only; the Lie
    closure is 3n.  This flag exists so a unit test can document the trap
    (rotation-only DLA is NOT su(2^n)); it must NOT be used for the science.
    """
    base = rotation_generators(n)
    if include_entangler and n > 1:
        E = cnot_ring(n)
        base = base + [E @ g @ E.conj().T for g in base]
    return base


# ---------------------------------------------------------------------------
# the frame-induced (restricted, commutant) DLA -- the Representation-Dial knob
# ---------------------------------------------------------------------------
def symmetrized_generators(generators, rep):
    """Twirl each generator onto the commutant of the representation:
        P_mu^sym = (1/|G|) sum_g U_g P_mu U_g^dag .

    The result commutes with every U_g (Meyer et al. PRX Quantum 2023
    equivariant-ansatz construction), so the corresponding ansatz preserves
    H_+ = range(Pi) and its effective algebra is the restricted DLA g_G.
    """
    Us = rep.matrices
    m = rep.order
    return [sum(U @ g @ U.conj().T for U in Us) / m for g in generators]


def invariant_subspace_basis(rep, tol: float = 1e-9) -> np.ndarray:
    """Orthonormal columns B spanning H_+ = range(Pi), Pi = (1/|G|) sum U_g.

    Pi is a Hermitian projector (eigenvalues 0/1); we return the eigenvectors
    with eigenvalue 1.  Satisfies Pi B = B and B^dag B = I.
    """
    Pi = rep.projector()
    w, V = np.linalg.eigh((Pi + Pi.conj().T) / 2.0)
    return V[:, w > 1.0 - tol]


def restrict(op: np.ndarray, Bplus: np.ndarray) -> np.ndarray:
    """Compress an operator to the H_+ block: B^dag op B."""
    return Bplus.conj().T @ op @ Bplus


def _traceless(H: np.ndarray) -> np.ndarray:
    d = H.shape[0]
    return H - (np.trace(H) / d) * np.eye(d, dtype=complex)


def frame_induced_dla(rep, n: int, tol: float = 1e-9, cap: int | None = None):
    """Restricted circuit DLA g_G of the symmetrised (equivariant) ansatz on
    H_+.

    Symmetrise the HEA circuit generators onto the rep commutant, restrict each
    to H_+, take the traceless part (the DLA is a subalgebra of su(dim H_+)),
    and Lie-close.

    Returns
    -------
    (d_eff, basis_rows, Bplus) : (int, (d_eff, |H_+|**2) array, (dim, |H_+|) array)
        d_eff = dim(g_G); basis_rows = orthonormal HS basis of g_G on H_+;
        Bplus = the H_+ basis (columns).
    """
    Bplus = invariant_subspace_basis(rep, tol)
    dim_hplus = Bplus.shape[1]
    if dim_hplus <= 1:
        # H_+ is 0- or 1-dimensional: su is trivial.
        return 0, np.zeros((0, dim_hplus ** 2), dtype=complex), Bplus
    gens = symmetrized_generators(hea_circuit_generators(n), rep)
    rgens = [_traceless(restrict(g, Bplus)) for g in gens]
    d_eff, basis = lie_closure_dim(rgens, tol=tol, cap=cap)
    return d_eff, basis, Bplus


# ---------------------------------------------------------------------------
# g-purity and the exact Ragone-Fontana variance law
# ---------------------------------------------------------------------------
def g_purity(H: np.ndarray, dla_basis: np.ndarray) -> float:
    """P_g(H) = sum_j |Tr[B_j^dag H]|^2 = || proj of H onto g ||_HS^2.

    `dla_basis` rows are an ORTHONORMAL (HS) basis {B_j} of g.  H is
    traceless-projected first (the DLA lives in su).  For H in g this returns
    ||H||_HS^2; for H orthogonal to g it returns ~0.
    """
    if dla_basis is None or dla_basis.shape[0] == 0:
        return 0.0
    H = _traceless(np.asarray(H, dtype=complex))
    coeffs = dla_basis.conj() @ H.reshape(-1)
    return float(np.sum(np.abs(coeffs) ** 2))


def ragone_variance(rho: np.ndarray, O: np.ndarray, dla_basis: np.ndarray,
                    d_eff: int) -> float:
    """Ragone-Fontana Eq. 10 gradient-variance prediction:
        Var = P_g(rho) P_g(O) / dim(g) .

    Exact only under the deep-2-design hypothesis (the ansatz forms an
    approximate 2-design over exp(g)).  For a shallow circuit this is a
    trend/order-of-magnitude cross-check, NOT an equality -- state so.
    """
    if d_eff <= 0 or dla_basis is None or dla_basis.shape[0] == 0:
        return 0.0
    return g_purity(rho, dla_basis) * g_purity(O, dla_basis) / float(d_eff)
